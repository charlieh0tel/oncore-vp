    @Override
    public void run() throws Exception {
        int fn = 0, lb = 0, kept = 0;
        for (String[] e : NAMES) {
            Address a = toAddr(Long.parseLong(e[0], 16));
            if (e[2].equals("F")) {
                if (getInstructionAt(a) == null) disassemble(a);
                Function f = getFunctionAt(a);
                if (f == null) f = createFunction(a, e[1]);
                if (f == null) { println("no function at " + a); continue; }
                if (f.getSymbol().getSource() == SourceType.DEFAULT || f.getName().equals(e[1])) {
                    f.setName(e[1], SourceType.USER_DEFINED); fn++;
                } else { println("kept " + f.getName() + " at " + a); kept++; }
            } else {
                Symbol s = getSymbolAt(a);
                if (s == null || s.getSource() == SourceType.DEFAULT) {
                    createLabel(a, e[1], true, SourceType.USER_DEFINED); lb++;
                } else if (!s.getName().equals(e[1])) {
                    createLabel(a, e[1], false, SourceType.USER_DEFINED); lb++;
                }
            }
        }
        println(fn + " functions named, " + lb + " labels, " + kept + " kept");
    }
