// 6ch copy of tools/ghidra/OncoreExportC.java (notes from tools/ghidra-6ch).
// Decompiles every function to one C file, in address order, and prints
// counts of named and unnamed functions.  Each function is preceded by its
// address and, where names-*.tsv has one, its note.  Argument: output file.
//@category Oncore

import ghidra.app.decompiler.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.SourceType;
import java.io.*;
import java.nio.file.*;
import java.util.*;

public class Oncore6ExportC extends GhidraScript {
    @Override
    public void run() throws Exception {
        File out = new File(getScriptArgs()[0]);
        // Function notes; later files win, as in OncoreNames.java.
        Map<Long, String> notes = new HashMap<>();
        File dir = getSourceFile().getParentFile().getFile(false);
        File[] tsv = dir.listFiles((d, s) -> s.startsWith("names-") && s.endsWith(".tsv"));
        Arrays.sort(tsv);
        for (File t : tsv) {
            for (String line : Files.readAllLines(t.toPath())) {
                String[] c = line.split("\t");
                if (line.startsWith("#") || c.length < 4 || !c[1].equals("F")) continue;
                String note = c[3].trim();
                if (note.isEmpty() || note.startsWith("docs/")) continue;
                notes.put(Long.parseLong(c[0], 16), note);
            }
        }
        DecompInterface di = new DecompInterface();
        di.openProgram(currentProgram);
        int n = 0, named = 0, failed = 0;
        try (PrintWriter w = new PrintWriter(new FileWriter(out))) {
            w.println("/*");
            w.println(" * Motorola VP Oncore B1121P1114 6ch (SFTW 98-P39972M VER 8 REV 4, 13 Jul 1995).");
            w.println(" * Ghidra decompiler output, regenerated by tools/ghidra-6ch (Oncore6ExportC.java);");
            w.println(" * names from tools/ghidra-6ch/names-*.tsv.");
            w.println(" * Derived from the vendor flash image; not covered by this repository's");
            w.println(" * license.  Not compilable as is.");
            w.println(" */\n");
            for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
                if (monitor.isCancelled()) break;
                n++;
                if (f.getSymbol().getSource() != SourceType.DEFAULT) named++;
                DecompileResults r = di.decompileFunction(f, 60, monitor);
                String note = notes.get(f.getEntryPoint().getOffset());
                w.println("/* " + f.getEntryPoint() + (note != null ? ": " + note : "") + " */");
                if (r.decompileCompleted()) w.println(r.getDecompiledFunction().getC());
                else { failed++; w.println("/* decompile failed: " + r.getErrorMessage() + " */\n"); }
            }
        }
        println(n + " functions, " + named + " named, " + failed + " failed");
    }
}
